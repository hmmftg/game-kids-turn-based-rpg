/**
 * Generates the R3F component stub for a shipped vertex-baked GLB
 * (scripts/convert-model.ts --vcolor → one joined mesh per file).
 *
 * Usage:
 *   node --experimental-strip-types scripts/gen-gltf-component.ts \
 *     [--ds] <public/models/foo.glb> [ComponentName] [more.glb ...]
 *
 * ComponentName defaults to the PascalCase file basename; output lands in
 * src/world/models/gltf/<ComponentName>.tsx and is skipped if it exists
 * (pass --force to overwrite — but preserve the header's review notes).
 * Multi-mesh files emit one <mesh> per mesh-bearing node.
 * `--ds` binds the double-sided VERTEX_LAMBERT_DS — required when
 * convert-model.ts reports "doubleSided": true for the source material
 * (Sketchfab auto-rigged models rely on backfaces; single-sided culling
 * breaks them into black shards).
 *
 * The emitted file carries the repo's GLB invariants by construction:
 * BASE_URL-relative MODEL_URL, no module-scope useGLTF.preload,
 * raycast={noRaycast} on every mesh, shared VERTEX_LAMBERT material.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(repoRoot, 'src/world/models/gltf');

const args = process.argv.slice(2).filter((a) => a !== '--force' && a !== '--ds');
const force = process.argv.includes('--force');
const doubleSided = process.argv.includes('--ds');
const materialName = doubleSided ? 'VERTEX_LAMBERT_DS' : 'VERTEX_LAMBERT';
if (args.length === 0) {
  console.error('usage: gen-gltf-component.ts <public/models/foo.glb> [ComponentName] ...');
  process.exit(1);
}

const pascal = (s: string) =>
  s
    .replace(/\.[^.]+$/, '')
    .split(/[-_./\s]+/)
    .filter(Boolean)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join('');
const isIdent = (s: string) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(s);
const key = (s: string) => (isIdent(s) ? s : `'${s.replace(/'/g, "\\'")}'`);
const access = (s: string) => (isIdent(s) ? `.${s}` : `[${key(s)}]`);

const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);

interface Job {
  readonly glb: string;
  readonly component: string;
}
const jobs: Job[] = [];
for (let i = 0; i < args.length; i++) {
  const glb = args[i]!;
  const next = args[i + 1];
  const named = next !== undefined && !next.endsWith('.glb');
  jobs.push({ glb, component: named ? next! : pascal(basename(glb)) });
  if (named) i++;
}

for (const { glb, component } of jobs) {
  const out = join(outDir, `${component}.tsx`);
  if (existsSync(out) && !force) {
    console.error(`skip ${relative(repoRoot, out)} (exists — pass --force to regenerate)`);
    continue;
  }
  const doc = await io.read(glb);
  const nodeNames = [
    ...new Set(
      doc
        .getRoot()
        .listNodes()
        .filter((n) => n.getMesh())
        .map((n) => n.getName()),
    ),
  ];
  if (nodeNames.length === 0) {
    console.error(`skip ${glb}: no mesh-bearing nodes`);
    continue;
  }
  const glbName = basename(glb);
  const meshes = nodeNames
    .map(
      (n) => `      <mesh
        name=${JSON.stringify(n)}
        geometry={nodes${access(n)}.geometry}
        material={${materialName}}
        raycast={noRaycast}
      />`,
    )
    .join('\n');
  const source = `/*
Auto-generated by: scripts/gen-gltf-component.ts
Command: node --experimental-strip-types scripts/gen-gltf-component.ts ${doubleSided ? '--ds ' : ''}public/models/${glbName} ${component}

Reviewed + adapted for this repo (edit by hand after regenerating):
- URL pinned to MODEL_URL — \`import.meta.env.BASE_URL\`-relative so subpath
  deploys work (vite.config.ts uses \`base: './'\`; check-deploy rejects
  root-absolute refs).
- The generator's module-scope \`useGLTF.preload(...)\` is removed on purpose:
  importing this module must not fetch while another ModelSet is active.
- Every mesh is \`raycast={noRaycast}\` — decorative only; taps live on the
  explicit proxies/props that wrap these models.
- The GLB is vertex-colored (convert-model.ts --vcolor): the shared
  ${materialName} shades it — see materials.ts.${doubleSided ? '\n- --ds: the source material was doubleSided (see convert output);\n  VERTEX_LAMBERT_DS keeps its backfaces shaded.' : ''}
*/

import type * as THREE from 'three';
import type { ThreeElements } from '@react-three/fiber';
import { useGLTF } from '@react-three/drei';
import type { GLTF } from 'three-stdlib';
import { noRaycast } from '../raycast.ts';
import { ${materialName} } from './materials.ts';

const MODEL_URL = \`\${import.meta.env.BASE_URL}models/${glbName}\`;

type GLTFResult = GLTF & {
  nodes: {
${nodeNames.map((n) => `    ${key(n)}: THREE.Mesh;`).join('\n')}
  };
};

export function ${component}(props: ThreeElements['group']) {
  const { nodes } = useGLTF(MODEL_URL) as unknown as GLTFResult;
  return (
    <group {...props} dispose={null}>
${meshes}
    </group>
  );
}
`;
  mkdirSync(outDir, { recursive: true });
  writeFileSync(out, source);
  console.log(
    `wrote ${relative(repoRoot, out)} (${nodeNames.length} mesh${nodeNames.length === 1 ? '' : 'es'})`,
  );
}
